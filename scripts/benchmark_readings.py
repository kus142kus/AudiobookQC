"""Independent editorial accuracy benchmark for AudiobookQC.

No speech-model downloads; works with human-verified CSV annotations. This does
NOT claim to validate ASR accuracy without real labelled audio. A finding must
match at most one human-confirmed error in a +/- time window. Do not include
unverified model output as ground truth.

Usage:
 python scripts/benchmark_readings.py --truth truth.csv --findings findings.csv \\
   --output benchmark.json --duration-hours 0.25 --docx benchmark.docx

For a Word report generated by the program, first extract possible issues to
CSV using --extract-docx; CHECK this extraction manually before benchmarking.
"""
from __future__ import annotations

import argparse
from collections import Counter
import csv
from dataclasses import asdict, dataclass
import json
from pathlib import Path
import re
import sys


TIME_RE = re.compile(r'^\s*(\d+):(\d{2}):(\d{2})(?:[.,](\d{1,3}))?\s*$')
SHORT_TIME_RE = re.compile(r'^\s*(\d+):(\d{2})(?:[.,](\d{1,3}))?\s*$')
IMPORTANT = {'high', 'critical', 'major', 'important', '1', 'true', 'yes',
             'высокий', 'важно', 'существенная', 'существенно', 'критическая', 'критично'}
MINOR = {'minor', 'low', 'review', 'sound', 'uncertain', '0', 'false', 'no',
         'низкий', 'неважно', 'сомнительно', 'неуверенно', 'проверить', 'звук',
         'незначительная', 'незначительно'}
KINDS = {
    'replacement': 'replacement', 'substitution': 'replacement', 'замена': 'replacement',
    'omission': 'omission', 'missing': 'omission', 'пропуск': 'omission',
    'repeat': 'repeat', 'retake': 'repeat', 'повтор': 'repeat', 'самопоправка': 'repeat',
    'extra': 'extra', 'addition': 'extra', 'вставка': 'extra', 'лишнее': 'extra',
    'negation': 'negation', 'отрицание': 'negation',
    'number': 'number', 'число': 'number', 'цифра': 'number',
    'name': 'name', 'имя': 'name',
    'stress': 'stress', 'ударение': 'stress',
    'sound': 'sound', 'звук': 'sound',
}


def seconds(value: object) -> float:
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if float(value) < 0:
            raise ValueError('Time must be nonnegative')
        return float(value)
    raw = str(value or '').strip()
    match = TIME_RE.fullmatch(raw)
    if match:
        h, m, sec, milli = match.groups()
        if int(m) >= 60 or int(sec) >= 60:
            raise ValueError(f'Invalid HH:MM:SS timestamp: {raw}')
        return int(h)*3600 + int(m)*60 + int(sec) + float('0.' + milli) if milli else int(h)*3600 + int(m)*60 + int(sec)
    match = SHORT_TIME_RE.fullmatch(raw)
    if match:
        m, sec, milli = match.groups()
        if int(sec) >= 60:
            raise ValueError(f'Invalid MM:SS timestamp: {raw}')
        return int(m)*60 + int(sec) + float('0.' + milli) if milli else int(m)*60 + int(sec)
    try:
        result = float(raw.replace(',', '.'))
    except ValueError as exc:
        raise ValueError(f'Invalid timestamp {raw!r}; use HH:MM:SS or seconds') from exc
    if not 0 <= result < float('inf'):
        raise ValueError(f'Invalid timestamp: {raw}')
    return result


def hhmmss(ts: float) -> str:
    rounded = int(ts)
    return f'{rounded//3600:02}:{rounded%3600//60:02}:{rounded%60:02}'


def pick(row: dict[str, str], *keys: str) -> str:
    lowered = {str(k).strip().casefold(): str(v or '').strip() for k, v in row.items() if k is not None}
    for key in keys:
        if key.casefold() in lowered:
            return lowered[key.casefold()]
    return ''


def kind_name(value: str) -> str:
    norm = str(value or '').strip().casefold()
    return KINDS.get(norm, norm or 'unspecified')


@dataclass(frozen=True)
class Finding:
    time: float
    kind: str
    expected: str = ''
    heard: str = ''
    importance: str = 'high'
    source_row: int = 0


def load_csv(path: str | Path, *, truth: bool = False,
             include_minor: bool = False) -> tuple[list[Finding], int]:
    path = Path(path)
    with path.open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream)
        if not reader.fieldnames:
            raise ValueError(f'Empty CSV: {path}')
        possible = ('time', 'timestamp', 'timestamp_seconds', 'start',
                    'start_seconds', 'таймкод', 'время', 'время начала')
        if not any(key in [x.strip().casefold() for x in reader.fieldnames] for key in possible):
            raise ValueError(f'{path}: a time/timestamp/таймкод column is required')
        records = []
        ignored = 0
        for rownum, row in enumerate(reader, 2):
            if not any(str(v or '').strip() for v in row.values()):
                continue
            t = pick(row, *possible)
            try:
                timestamp = seconds(t)
            except ValueError as exc:
                raise ValueError(f'{path}:{rownum}: {exc}') from exc
            importance = pick(row, 'importance', 'severity', 'priority', 'важность', 'приоритет')
            if not importance:
                importance = 'high' if truth else 'review'
            lower = importance.casefold()
            if lower in MINOR and not include_minor:
                ignored += 1
                continue
            if lower not in IMPORTANT and lower not in MINOR:
                raise ValueError(f'{path}:{rownum}: unknown importance {importance!r}; '
                                 'use high/major or review/minor')
            records.append(Finding(timestamp,
                                   kind_name(pick(row, 'kind', 'type', 'category', 'тип', 'ошибка')),
                                   pick(row, 'expected', 'original', 'по тексту', 'верно'),
                                   pick(row, 'heard', 'spoken', 'recognized', 'распознано', 'услышано'),
                                   importance=lower, source_row=rownum))
    return records, ignored


def match_all(truth: list[Finding], findings: list[Finding], *, tolerance: float = 5.,
              strict_kind: bool = False) -> list[tuple[int, int]]:
    """Maximum cardinality one-to-one bipartite matches, nearest candidates first."""
    if tolerance < 0:
        raise ValueError('Tolerance must be nonnegative')
    edges = []
    for t in truth:
        candidates = [(i, abs(t.time - f.time)) for i, f in enumerate(findings)
                      if abs(t.time-f.time) <= tolerance
                      and (not strict_kind or t.kind == f.kind)]
        candidates.sort(key=lambda p: (p[1], p[0]))
        edges.append([i for i, _ in candidates])
    pred_to_truth: dict[int, int] = {}

    def augment(i: int, seen: set[int]) -> bool:
        for j in edges[i]:
            if j in seen:
                continue
            seen.add(j)
            if j not in pred_to_truth or augment(pred_to_truth[j], seen):
                pred_to_truth[j] = i
                return True
        return False

    # Handle the most constrained truth entries first; avoids some greedy pathologies.
    for i in sorted(range(len(truth)), key=lambda i: (len(edges[i]), truth[i].time)):
        augment(i, set())
    return sorted(((i, j) for j, i in pred_to_truth.items()), key=lambda p: p[0])


def evaluate(truth: list[Finding], findings: list[Finding], *, tolerance: float = 5.,
             strict_kind: bool = False, duration_hours: float | None = None,
             ignored_truth: int = 0, ignored_findings: int = 0) -> dict:
    if duration_hours is not None and duration_hours <= 0:
        raise ValueError('duration_hours must be positive')
    matches = match_all(truth, findings, tolerance=tolerance, strict_kind=strict_kind)
    truth_hit = {i for i, _ in matches}
    found_hit = {j for _, j in matches}
    tp, fp, fn = len(matches), len(findings)-len(matches), len(truth)-len(matches)
    precision = tp/(tp+fp) if tp+fp else (1. if not truth else 0.)
    recall = tp/(tp+fn) if tp+fn else 1.
    f1 = 2*precision*recall/(precision+recall) if precision+recall else 0.
    by_kind: dict[str, dict] = {}
    for kind in sorted({r.kind for r in truth}):
        total = sum(r.kind == kind for r in truth)
        hit = sum(truth[i].kind == kind for i in truth_hit)
        by_kind[kind] = {'found': hit, 'total': total, 'recall': hit/total if total else 1.}
    def detail(obj: Finding) -> dict:
        result = asdict(obj)
        result['time_hhmmss'] = hhmmss(obj.time)
        return result
    return {
        'policy': {'tolerance_seconds': tolerance, 'strict_kind': strict_kind,
                   'only_substantial_errors': ignored_truth >= 0 and ignored_findings >= 0},
        'totals': {'truth': len(truth), 'findings': len(findings), 'true_positive': tp,
                   'false_positive': fp, 'false_negative': fn,
                   'excluded_minor_truth': ignored_truth, 'excluded_minor_findings': ignored_findings},
        'precision': round(precision, 6), 'recall': round(recall, 6), 'f1': round(f1, 6),
        'false_alerts_per_hour': round(fp/duration_hours, 4) if duration_hours else None,
        'by_kind': by_kind,
        'matches': [{'truth': detail(truth[i]), 'finding': detail(findings[j]),
                     'delta_seconds': round(findings[j].time-truth[i].time, 3)} for i, j in matches],
        'false_alarms': [detail(f) for j, f in enumerate(findings) if j not in found_hit],
        'missed': [detail(t) for i, t in enumerate(truth) if i not in truth_hit],
    }


def report_docx(stats: dict, out: str | Path) -> None:
    from docx import Document  # optional when writing Word only
    doc = Document()
    doc.add_heading('AudiobookQC — независимая оценка точности', 0)
    doc.add_paragraph('Основа: ошибки, заранее подтверждённые прослушиванием, и '
                      'существенные замечания приложения. Один найденный случай '
                      'может соответствовать только одной реальной ошибке.')
    doc.add_heading('Итоги', level=1)
    totals = stats['totals']
    doc.add_paragraph(f"Найдено верно: {totals['true_positive']} | "
                      f"Ложных тревог: {totals['false_positive']} | "
                      f"Пропущено: {totals['false_negative']}")
    doc.add_paragraph(f"Точность: {stats['precision']:.1%} | "
                      f"Полнота: {stats['recall']:.1%} | F1: {stats['f1']:.1%}")
    if stats['false_alerts_per_hour'] is not None:
        doc.add_paragraph(f"Ложных тревог за час: {stats['false_alerts_per_hour']}")
    for title, key in (('Пропущенные существенные ошибки', 'missed'),
                       ('Ложные тревоги приложения', 'false_alarms')):
        doc.add_heading(title, level=1)
        rows = stats[key]
        if not rows:
            doc.add_paragraph('Не обнаружены на представленном наборе.')
            continue
        table = doc.add_table(rows=1, cols=4)
        table.style = 'Table Grid'
        for cell, text in zip(table.rows[0].cells, ('Время', 'Тип', 'По тексту', 'В записи')):
            cell.text = text
        for item in rows:
            cells = table.add_row().cells
            for cell, text in zip(cells, (item['time_hhmmss'], item['kind'],
                                          item['expected'], item['heard'])):
                cell.text = text[:400]
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    doc.save(out)


def extract_docx(source: str | Path, output: str | Path) -> int:
    """Extract *candidates*; do not invent verification/importance from Word.

    Table columns are detected by headers. Every extracted row is marked review,
    so it will be excluded from high-confidence scoring until a human verifies
    that it belongs to the main corrections section.
    """
    from docx import Document
    doc = Document(source)
    records = []
    for table in doc.tables:
        if len(table.rows) < 2:
            continue
        headers = [c.text.casefold().strip() for c in table.rows[0].cells]
        def idx(parts: tuple[str, ...]) -> int | None:
            return next((i for i, h in enumerate(headers) if any(p in h for p in parts)), None)
        t_idx = idx(('время', 'таймкод', 'timestamp'))
        exp_idx = idx(('по тексту', 'оригинал', 'верный', 'expected'))
        heard_idx = idx(('распознано', 'озвучено', 'услышано', 'recognized', 'heard'))
        if t_idx is None or exp_idx is None or heard_idx is None:
            continue
        for row in table.rows[1:]:
            values = [c.text.strip() for c in row.cells]
            if max(t_idx, exp_idx, heard_idx) >= len(values):
                continue
            try:
                t = seconds(values[t_idx])
            except ValueError:
                continue
            if not values[exp_idx] and not values[heard_idx]:
                continue
            records.append({'time': hhmmss(t), 'kind': 'unspecified',
                            'expected': values[exp_idx], 'heard': values[heard_idx],
                            'importance': 'review'})
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', encoding='utf-8-sig', newline='') as out:
        writer = csv.DictWriter(out, fieldnames=['time', 'kind', 'expected', 'heard', 'importance'])
        writer.writeheader()
        writer.writerows(records)
    return len(records)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description='AudiobookQC: truth-vs-findings accuracy benchmark')
    parser.add_argument('--truth', type=Path)
    parser.add_argument('--findings', type=Path)
    parser.add_argument('--output', type=Path, default=Path('benchmark.json'))
    parser.add_argument('--docx', type=Path)
    parser.add_argument('--tolerance', type=float, default=5.)
    parser.add_argument('--strict-kind', action='store_true')
    parser.add_argument('--duration-hours', type=float)
    parser.add_argument('--include-minor', action='store_true')
    parser.add_argument('--min-precision', type=float)
    parser.add_argument('--min-recall', type=float)
    parser.add_argument('--extract-docx', type=Path)
    parser.add_argument('--output-csv', type=Path)
    args = parser.parse_args(argv)
    if args.extract_docx:
        if not args.output_csv:
            parser.error('--extract-docx requires --output-csv')
        found = extract_docx(args.extract_docx, args.output_csv)
        print(f'Extracted {found} UNVERIFIED report candidates to {args.output_csv}', flush=True)
        return 0
    if not args.truth or not args.findings:
        parser.error('--truth and --findings are both required')
    for name in ('min_precision', 'min_recall'):
        val = getattr(args, name)
        if val is not None and not 0 <= val <= 1:
            parser.error(f'{name}: expected a number from 0 to 1')
    truth, ignored_truth = load_csv(args.truth, truth=True, include_minor=args.include_minor)
    pred, ignored_pred = load_csv(args.findings, include_minor=args.include_minor)
    stats = evaluate(truth, pred, tolerance=args.tolerance,
                     strict_kind=args.strict_kind, duration_hours=args.duration_hours,
                     ignored_truth=ignored_truth, ignored_findings=ignored_pred)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(stats, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    if args.docx:
        report_docx(stats, args.docx)
    print(f"TP={stats['totals']['true_positive']} FP={stats['totals']['false_positive']} "
          f"FN={stats['totals']['false_negative']} "
          f"P={stats['precision']:.1%} R={stats['recall']:.1%} F1={stats['f1']:.1%}", flush=True)
    if ((args.min_precision is not None and stats['precision'] < args.min_precision) or
            (args.min_recall is not None and stats['recall'] < args.min_recall)):
        print('ACCURACY_GATE_FAILED: criteria not met; do not claim production accuracy', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
